def get_expert_by_type(expert_type: str) -> dict:
    """根据专家类型获取配置

    Args:
        expert_type: 专家类型标识（如 'oncology', 'respiratory'）

    Returns:
        专家配置字典，未找到返回 None
    """
    for expert_name, config in MEDICAL_EXPERTS.items():
        if config["expert_type"] == expert_type:
            return {
                "expert_name": expert_name,
                **config
            }
    return None


def get_all_expert_types() -> list:
    """获取所有专家类型列表

    Returns:
        专家类型列表 [{'name': '肿瘤科专家', 'type': 'oncology', 'priority': 1}, ...]
    """
    return [
        {
            "name": expert_name,
            "type": config["expert_type"],
            "priority": config["priority"]
        }
        for expert_name, config in MEDICAL_EXPERTS.items()
    ]


def get_expert_keywords(expert_type: str) -> list:
    """获取指定专家的关键词列表

    Args:
        expert_type: 专家类型标识

    Returns:
        关键词列表
    """
    expert = get_expert_by_type(expert_type)
    return expert.get("keywords", []) if expert else []
